export function normalizeLanguage(value: unknown): AppLanguage { return value === "sk" ? "sk" : "en"; }

export function translate(language: AppLanguage, key: string): string {
  if (language === "en") return EN[key] ?? key;
  return TRANSLATIONS[language]?.[key] ?? EN[key] ?? key;
}
